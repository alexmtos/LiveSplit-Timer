  // Expose translation map for debugging if needed
  window.TRANSLATIONS = _translations;

  // Simple language detector (browser-based) and a universal translate function
  function _detectLang() {
    if (typeof navigator === 'undefined') return 'pt-BR';
    const lang = navigator.language || navigator.userLanguage || 'pt-BR';
    const code = lang.toLowerCase();
    if (code.startsWith('en')) return 'en-US';
    if (code.startsWith('pt')) return 'pt-BR';
    if (code.startsWith('fr')) return 'fr';
    if (code.startsWith('de')) return 'de';
    if (code.startsWith('es')) return 'es';
    // fallback for others
    return 'pt-BR';
  }

  window.getTranslation = function (key) {
    // Prefer explicit APP_CONFIG.LANG if provided by the new config system
    const lang = (window.APP_CONFIG && window.APP_CONFIG.LANG) || _detectLang();
    const bucket = _translations[lang] || _translations['pt-BR'];
    // If nested keys are used in future (e.g., 'timer.start'), support simple flat keys here
    return bucket[key] || key;
  };

  // Apply translations to all elements with data-translate attribute
  window.applyAllTranslations = function () {
    if (typeof window.getTranslation !== 'function') return;

    // 1. Translate all elements with data-translate attribute (textContent)
    document.querySelectorAll('[data-translate]').forEach(el => {
      const key = el.getAttribute('data-translate');
      if (key) {
        el.textContent = window.getTranslation(key);
      }
    });

    // 2. Translate elements with data-translate-attr (attribute-based translations)
    // Format: data-translate-attr="attr1:key1;attr2:key2"
    document.querySelectorAll('[data-translate-attr]').forEach(el => {
      const attrSpec = el.getAttribute('data-translate-attr');
      if (!attrSpec) return;
      const pairs = attrSpec.split(';');
      pairs.forEach(pair => {
        const [attr, key] = pair.split(':').map(s => s.trim());
        if (attr && key) {
          el.setAttribute(attr, window.getTranslation(key) || el.getAttribute(attr));
        }
      });
    });

    // 3. Update version label in modal footer (special case: has version number appended)
    const versionEl = document.getElementById('app-version');
    if (versionEl) {
      const label = window.getTranslation('version_label') || 'Versão';
      const ver = (window.APP_CONFIG && window.APP_CONFIG.VERSION) || '1.0.0';
      versionEl.textContent = `${label} ${ver}`;
    }

    // 4. Update connection status text based on indicator dot state
    const connStatusEl = document.getElementById('connection-status-text');
    const dot = document.getElementById('connection-indicator-dot');
    if (connStatusEl && dot) {
      let key = 'connection_disconnected';
      if (dot.classList.contains('connected')) key = 'connection_status';
      else if (dot.classList.contains('connecting')) key = 'connection_connecting';
      connStatusEl.textContent = window.getTranslation(key) || connStatusEl.textContent;
    }

    // 5. Update button titles that were set dynamically (legacy support)
    const titleMap = {
      'Pause': 'tooltip_pause',
      'Resume': 'tooltip_resume',
      'Start': 'tooltip_start',
      'Split': 'tooltip_split',
      'Reset': 'tooltip_reset',
      'Undo': 'tooltip_undo',
      'Skip': 'tooltip_skip'
    };
    Object.keys(titleMap).forEach(origText => {
      const key = titleMap[origText];
      document.querySelectorAll(`[title="${origText}"]`).forEach(el => {
        el.title = window.getTranslation(key) || el.title;
      });
    });
  };
